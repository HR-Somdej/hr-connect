function helpKey() {
  var r = S.route, tab = S.wsTab, ev;
  if (r === 'event') {
    var id = (location.hash.split('/')[2] || '').split('?')[0];
    ev = (S.boot.events || []).filter(function (e) { return e.id === id; })[0];
    return ev && ev.type === 'ORDER' ? 'eventOrder' : 'eventChoice';
  }
  if (r === 'admin/ev') {
    if (tab === 'settings') return 'settingsEv';
    return HELP[tab] ? tab : 'overview';
  }
  if (r === 'admin/settings') {
    var st = location.hash.split('/')[3] || 'general';
    return { admins: 'stAdmins', api: 'stApi', audit: 'stAudit' }[st] || 'stGeneral';
  }
  return { 'admin/events': 'events', 'admin/roster': 'roster', 'admin/heads': 'heads', home: 'home' }[r] || 'home';
}
function manualUrl(anchor) { return 'manual.html?v=' + HRC_BUILD + (anchor ? '#' + anchor : ''); }
function openHelp(key) {
  key = key || helpKey();
  var h = HELP[key] || HELP.home;
  var headNote = S.me && !isAdmin() && isHead() && /overview|tracking|reports|print/.test(key) ? '<div class="announce">' + ic('info') + '<div>คุณเข้าในฐานะ <b>หัวหน้า</b> เห็นเฉพาะสังกัดของคุณ และดูได้อย่างเดียว</div></div>' : '';
  modal({ title: ic('help') + ' วิธีใช้: ' + h.t, size: 'md',
    body: headNote + '<ol class="helpsteps">' + h.s.map(function (x) { return '<li>' + x + '</li>'; }).join('') + '</ol>' +
      (h.tip && h.tip.length ? '<div class="helptips"><b>' + ic('info') + ' เคล็ดลับ</b><ul>' + h.tip.map(function (x) { return '<li>' + x + '</li>'; }).join('') + '</ul></div>' : '') +
      '<div class="small muted" style="margin-top:12px">ติดขัด สอบถาม ฝ่ายทรัพยากรบุคคล โทร 25400 - 23419</div>',
    foot: '<a class="btn" href="' + manualUrl(h.a) + '" target="_blank" rel="noopener">' + ic('book') + 'คู่มือฉบับเต็ม (มีภาพประกอบ)</a><button class="btn primary" data-x>เข้าใจแล้ว</button>' });
}
